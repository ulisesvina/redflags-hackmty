"""Typed, in-memory view of a dataset (#2), from either schema (#79).

Every detector (#4-#11), the tool layer (#12) and the guard (#14) build on this.
Load rules (see docs/ISSUES.md #2):
- Read every CSV with dtype=str, keep_default_na=False: empty cells stay "", never NaN.
- Convert dates to datetime64 and money/quantities to float64 afterwards.
- Everything else stays str; CLABEs, folio, po_number, account_code must keep
  their leading zeros.
- Never opens anything the agent is not allowed to see.

``load(path)`` accepts three inputs and returns the same :class:`Dataset`:

1. our legacy CSV directory (it has ``suppliers.csv``);
2. a judges' estate as SQLite (``path`` is a file that opens with a ``vendors`` table);
3. a judges' estate as a CSV directory (it has ``vendors.csv``).

The judges' eight tables (``estate_schema.sql``) are adapted onto our frames by the
mapping in ``docs/SPEC_GAP.md``, so the detectors, tools and guard work unchanged on
estates generated by someone else. Two adaptations are worth knowing about:

**Purchase orders stand in for goods receipts.** The judges' schema has no
``goods_receipts`` table; a purchase order is the only deliverable trail it carries.
Each invoice matched to a PO (same vendor, amount within a centavo, PO dated no later
than 30 days after the invoice) gets one synthetic receipt whose ``receipt_id`` is the
``po_id``, so "paid with no deliverable" detectors keep working and any exhibit they
cite resolves to a real ``purchase_orders`` row.

**Payments are linked to invoices by reference, then by amount.** Their ``bank_txns``
has no ``invoice_uuid``: a payment is tied to an invoice by an invoice id appearing in
the ``reference`` text, and failing that by counterparty CLABE plus an exact amount
match on or after the issue date, earliest unpaid invoice first. A payment that
matches nothing keeps an empty ``invoice_uuid`` rather than guessing.

``Dataset.source_format`` says which shape a dataset came from, and
``Dataset.record_table`` maps every record id to the judges' table it lives in, so a
finding's exhibits can name their ``source_table``.
"""
from __future__ import annotations

import json
import sqlite3
import sys
from dataclasses import dataclass, field
from pathlib import Path

import pandas as pd

DATE_COLUMNS = {
    "suppliers": ["onboarded"],
    "invoices": ["fecha", "fecha_timbrado"],
    "goods_receipts": ["fecha"],
    "bank_transactions": ["fecha"],
    "counterparty_bank": ["fecha"],
    "ledger": ["fecha"],
    "efos_69b": ["fecha_publicacion"],
    "purchase_orders": ["date"],
    "contracts": ["start_date"],
}

FLOAT_COLUMNS = {
    "invoices": ["cantidad", "valor_unitario", "subtotal", "iva", "total"],
    "goods_receipts": ["cantidad"],
    "bank_transactions": ["amount"],
    "counterparty_bank": ["amount"],
    "ledger": ["debit", "credit"],
    "purchase_orders": ["amount"],
    "contracts": ["value"],
}


@dataclass
class Dataset:
    path: Path
    company: dict  # company.json: name, rfc, clabe, city
    suppliers: pd.DataFrame  # supplier_id, name, rfc, street, city, clabe, account_holder, category, onboarded, approved_by, status
    customers: pd.DataFrame  # customer_id, name, rfc, street, city, clabe
    employees: pd.DataFrame  # employee_id, name, rfc, role, home_street, home_city, personal_clabe
    invoices: pd.DataFrame  # uuid, tipo, serie, folio, fecha, fecha_timbrado, rfc_emisor, nombre_emisor, rfc_receptor, nombre_receptor, uso_cfdi, forma_pago, metodo_pago, clave_prod_serv, descripcion, cantidad, valor_unitario, subtotal, iva, total, moneda, po_number, counterparty_id, approved_by
    goods_receipts: pd.DataFrame  # receipt_id, po_number, supplier_id, invoice_uuid, fecha, descripcion, cantidad, received_by, warehouse
    bank_transactions: pd.DataFrame  # txn_id, fecha, account_clabe, direction, amount, counterparty_name, counterparty_clabe, reference, invoice_uuid
    counterparty_bank: pd.DataFrame  # record_id, entity_name, entity_clabe, fecha, direction, amount, counterparty_name, counterparty_clabe, reference
    ledger: pd.DataFrame  # entry_id, fecha, account_code, account_name, debit, credit, descripcion, invoice_uuid, txn_id
    efos_69b: pd.DataFrame  # rfc, nombre, situacion, fecha_publicacion
    # Judges'-schema tables with no legacy equivalent; empty on a legacy load.
    purchase_orders: pd.DataFrame = field(default_factory=lambda: _empty_frame("purchase_orders"))
    contracts: pd.DataFrame = field(default_factory=lambda: _empty_frame("contracts"))
    # record id -> the judges' table it lives in, for a finding's exhibits.
    record_table: dict[str, str] = field(default_factory=dict)
    source_format: str = "legacy"  # "legacy" | "judges"

    def all_record_ids(self) -> set[str]:
        """Invoice uuids | txn_ids | counterparty record_ids | receipt_ids | PO | contract ids."""
        ids: set[str] = set(self.invoices["uuid"])
        ids.update(self.bank_transactions["txn_id"])
        ids.update(self.counterparty_bank["record_id"])
        ids.update(self.goods_receipts["receipt_id"])
        ids.update(self.purchase_orders["po_id"])
        ids.update(self.contracts["contract_id"])
        return ids

    def all_entity_ids(self) -> set[str]:
        """supplier_ids | customer_ids | employee_ids."""
        ids: set[str] = set(self.suppliers["supplier_id"])
        ids.update(self.customers["customer_id"])
        ids.update(self.employees["employee_id"])
        return ids


def _read_csv(path: Path) -> pd.DataFrame:
    return pd.read_csv(path, dtype=str, keep_default_na=False, encoding="utf-8")


def _convert(df: pd.DataFrame, stem: str, *, coerce: bool = False) -> pd.DataFrame:
    """Type the date and money columns of one frame.

    ``coerce`` is for estates we did not write: an unparseable date becomes NaT and a
    blank amount becomes 0.0 instead of raising. Our own CSVs stay strict, so a
    generator that starts emitting malformed dates fails loudly.
    """
    df = df.copy()
    for col in DATE_COLUMNS.get(stem, []):
        parsed = pd.to_datetime(df[col], errors="coerce") if coerce else pd.to_datetime(df[col])
        df[col] = parsed.astype("datetime64[ns]")
    for col in FLOAT_COLUMNS.get(stem, []):
        if coerce:
            df[col] = pd.to_numeric(df[col], errors="coerce").fillna(0.0).astype("float64")
        else:
            df[col] = df[col].astype("float64")
    return df


def load(path: str | Path) -> Dataset:
    """Load a legacy directory, a judges' ``.db`` or a judges' CSV directory."""
    root = Path(path)
    if root.is_dir() and (root / "suppliers.csv").exists():
        return _load_legacy(root)
    if root.is_file():
        return _from_judges(_read_judges_db(root), root)
    if root.is_dir() and (root / "vendors.csv").exists():
        return _from_judges(_read_judges_csv(root), root)
    raise FileNotFoundError(
        f"{root} is not a dataset: expected suppliers.csv (legacy), vendors.csv "
        f"(judges' CSV export) or a judges' SQLite estate"
    )


def _load_legacy(root: Path) -> Dataset:
    """Our own CSV layout, unchanged since #2."""
    frames: dict[str, pd.DataFrame] = {}
    for stem in (
        "suppliers",
        "customers",
        "employees",
        "invoices",
        "goods_receipts",
        "bank_transactions",
        "counterparty_bank",
        "ledger",
        "efos_69b",
    ):
        df = _read_csv(root / f"{stem}.csv")
        frames[stem] = _convert(df, stem)
    company = json.loads((root / "company.json").read_text(encoding="utf-8"))
    return Dataset(path=root, company=company, **frames)


